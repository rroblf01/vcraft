module vcraft_codegen

// Emitting the glue.
//
// The output is a V file in the user's own module, so the trampolines call their
// functions directly with no module prefix and no cross-module edge. It is
// ordinary V that a person can read and a person can debug.
//
// The shape of a trampoline is fixed. For a plain function:
//
//	fn vcraft_generated__wrap_add(self voidptr, args voidptr, nargs isize) voidptr {
//		if nargs != 2 { vcraft.wrong_nargs('add', 2, int(nargs)) return unsafe { nil } }
//		arg0 := vcraft.from_py_int_arg(args, 0, 'add', 'a') or { return unsafe { nil } }
//		arg1 := vcraft.from_py_int_arg(args, 1, 'add', 'b') or { return unsafe { nil } }
//		mut result := 0
//		defer { if message := recover() { vcraft.raise_panic(message) } }
//		result = add(arg0, arg1)
//		if vcraft.error_is_set() { return unsafe { nil } }
//		return vcraft.to_py_int(result).ptr
//	}
//
// The `defer` is what keeps a V panic, which calls exit(1), from taking the
// interpreter down. When one fires, `result` keeps its zero value and the
// `error_is_set` check turns that into a Python exception rather than a bogus
// value. Nothing the guard touches needs to survive the jump, because the
// exception state it sets lives on the C side.

import strings

// new_builder returns an empty builder.
//
// V's `strings.Builder.new()` returns the zero value rather than a value, so a
// one-line wrapper is clearer at the many call sites below than the cast is.
fn new_builder() strings.Builder {
	return strings.Builder{}
}

const generated_header = '// Code generated by vcraft. Do not edit.\n' +
	'// Regenerate with `vcraft build`; it is written to disk and overwritten.\n\n'

// emit_glue renders the glue file for a project.
pub fn emit_glue(p Project) string {
	mut w := new_builder()
	w.write_string(generated_header)
	w.write_string('module ${p.module}\n\n')
	w.write_string('import vcraft\n\n')
	w.write_string(glue_module_body(p))
	for f in p.funcs {
		w.write_string('\n')
		w.write_string(emit_bind_globals(f))
		w.write_string(emit_trampoline(f))
	}
	for e in p.errors {
		w.write_string('\n')
		w.write_string(emit_error_raiser(e))
	}
	for c in p.classes {
		w.write_string(emit_class(p, c))
		for m in c.methods {
			// `@[vc_eq]` and `@[vc_hash]` fill the type's slots rather than the method
			// table, and they are called from `richcompare` and `hash` rather than from
			// Python. Emitting them as methods would put a `state.(arg0, arg1)` in the
			// generated source, because two receivers are not a receiver plus arguments.
			if m.eq || m.hash {
				continue
			}
			w.write_string('\n')
			w.write_string(emit_bind_globals(m))
			if m.property {
				w.write_string(emit_property_trampoline(p, c, m))
			} else if m.static || m.classmethod {
				// A classmethod is the static shape with METH_CLASS: `self` is the class
				// CPython passes, and the V call still carries the receiver by name.
				w.write_string(emit_static_trampoline(m))
			} else {
				w.write_string(emit_method_trampoline(p, c, m))
			}
		}
	}
	return w.str()
}

// glue_module_body renders the module definition and the two entry points.
//
// The tables the type needs are module-level globals rather than locals, because
// CPython keeps reading them: `PyType_FromSpec` copies what it needs, but a
// PyMethodDef's name and doc pointers are borrowed for the life of the type.
//
// The module under construction is a global rather than a local of `pyinit`.
//
// Single-phase initialisation lets `pyinit` build a module and return it: CPython calls
// `PyInit_` once and is done. Multi-phase initialisation, which an abi3 build has to
// use, does not: `PyInit_` returns a module *definition*, the interpreter then calls the
// `Py_mod_exec` slot inside it, and the definition must still be alive at that point. A
// local in `pyinit` is a dangling pointer by then, and the interpreter reads it as a
// module and crashes with nothing in the generated source to explain it.
//
// So `pyinit` is a thin wrapper that builds into the global and returns whatever this
// build's API expects, and `exec` does the part that fills the module in. `pyinit` calls
// `exec` itself on a single-phase build, so there is one copy of that code rather than
// two that can disagree.
pub fn glue_module_body(p Project) string {
	mut w := new_builder()
	w.write_string('__global (\n')
	w.write_string("\tg_vc_module = vcraft.new_module('${p.package}', " +
		'${vstring_literal(module_docstring(p))})\n')
	// The type handles are globals because the comparison and hash slots reference them
	// and CPython calls those after `Py_mod_exec` has returned.
	for c in p.classes {
		// `mut x = ...` is not valid in a global block: V's global syntax wants the
		// mutability and the value in separate places, and a `mut` here is rejected with
		// "unexpected token `=`, expecting name".
		w.write_string('\t' + c.ctype + ' = vcraft.PyObj{}\n')
	}
	// The base tuple is a global because `PyType_FromSpec` borrows the tuple for the
	// duration of its call and the type keeps a reference to the base types afterwards. A
	// local would be freed before the interpreter could subclass anything.
	for c in p.classes {
		if c.base_index < 0 {
			continue
		}
		w.write_string('\tg_vc_bases_' + c.key + ' = vcraft.PyObj{}\n')
	}
	w.write_string(')\n\n')
	w.write_string("@[export: 'PyInit_${p.package}']\n")
	w.write_string('fn vcraft_generated__pyinit() voidptr {\n')
	// The mirrors of CPython's structs are checked before anything is built with
	// them. A drifted mirror reads and writes at the wrong offsets, and every later
	// symptom is a wild pointer inside the interpreter -- un-diagnosable -- while
	// this names the struct. The free-threaded object header is the case that
	// motivated it: the wrong `PyModuleDef` mirror segfaults in `PyUnicode_FromString`
	// on import with nothing pointing at the mirror.
	w.write_string('\tvcraft.check_layout() or { return unsafe { nil } }\n')
	// The `for` is emitted once and the body once per function. Writing the header
	// inside the generator's loop instead produces one `for` per function, all of them
	// nested, and the generated file does not compile.
	//
	// The loop variable is `fn_` rather than `f` because the generated loops share a
	// file with the generator's own, and V rejects a redefinition of an iteration
	// variable in the same scope.
	//
	// The header is written once and the body once per function. The signature differs
	// per function, so it cannot be hoisted out of the loop; the header can, and
	// writing it inside the generator's loop instead produces one `for` per function,
	// all of them nested, which does not compile.
	// One call per function, and the loop variable inside the generated source is
	// `fn_` because the generated loops share a file with the generator's own and V
	// rejects a redefinition of an iteration variable in the same scope.
	for f in p.funcs {
		flags := if f.params.len == 0 { 'vcraft.meth_noargs' } else {
			'vcraft.meth_fastcall_keywords'
		}
		w.write_string('\tg_vc_module.add_function_owned(' + vstring_literal(f.name) +
			', voidptr(' + f.trampoline + '), ' + flags + ',\n')
		w.write_string('\t\t${vstring_literal(python_signature(f))})\n')
	}
	w.write_string('\tg_vc_module.set_exec(voidptr(vcraft_generated__exec))\n')
	w.write_string('\tmodule := g_vc_module.seal()\n')
	w.write_string('\treturn module.ptr\n}\n\n')
	w.write_string('// vcraft_generated__exec populates the module.\n')
	w.write_string('//\n')
	w.write_string("// CPython calls this through the `Py_mod_exec` slot on an abi3 build, and\n")
	w.write_string('// `pyinit` calls it directly otherwise, so the same code fills the module in\n')
	w.write_string('// either way.\n')
	w.write_string('fn vcraft_generated__exec(module voidptr) int {\n')
	// Checked here as well as in `pyinit`: multi-phase initialisation never runs
	// `pyinit`'s body, so without this an abi3 build would skip the check entirely.
	w.write_string('\tvcraft.check_layout() or { return -1 }\n')
	// The state chain lives in thread-local storage, keyed once here. `exec` runs once
	// per import under the import lock on every path -- single-phase through `pyinit`,
	// multi-phase through the interpreter -- so by the time any trampoline runs, on any
	// thread, the key exists.
	w.write_string('\tvcraft.init_state()\n')
	// The method table has to be installed here rather than left to module creation:
	// under multi-phase initialisation the module arrives empty.
	//
	// The types are declared here rather than where they are created because the
	// comparison and hash slots need to name them and CPython calls those after `exec`
	// has returned. A local would be out of scope, and the generated file would not
	// compile at all -- which is a better failure than a type whose `__eq__` silently
	// compares identity because the slot was never filled.
	w.write_string('\tg_vc_module.install_functions(module) or { return -1 }\n')
	for c in p.classes {
		w.write_string(render_class_exec(p, c))
	}
	// Module-level constants, each a boxed literal attached under its own name. The
	// reference the boxer returns is stolen by `add_object_owned`, so nothing leaks.
	for cn in p.consts {
		w.write_string('\tvcraft.add_object_owned(module, ' + vstring_literal(cn.name) +
			', ' + const_value_expr(cn) + ')\n')
	}
	w.write_string('\t_ = module\n')
	w.write_string('\treturn 0\n}\n')
	return w.str()
}

// pyinterp renders a `${name}` the way it must appear in generated V source.
//
// V has no spelling for a literal `${` inside a double-quoted string, so a generator
// that emits interpolated code cannot write one directly. Splitting the string around
// the interpolation is the way out: the pieces are plain text and only the middle is
// this generator's own substitution.
// interp renders a `${name}` as it must appear in generated V source.
//
// V has no spelling for a literal `${` inside a double-quoted string, so a generator
// that emits interpolated code cannot write one directly: unescaped, V tries to
// interpolate the name here, where it is not in scope. Splitting the literal into the
// pieces around the interpolation is the way out — `'${'` and `'}'` are ordinary text.
pub fn interp(name string) string {
	// The dollar is written as a byte rather than as `${`, because a `${` inside a
	// double-quoted V string is an interpolation and V tries to evaluate it here.
	return '$' + '{' + name + '}'
}

// const_stub_type is the Python type a `@[vc_const]` appears as in the `.pyi`.
fn const_stub_type(kind string) string {
	return match kind {
		'int' { 'int' }
		'float' { 'float' }
		'bool' { 'bool' }
		'str' { 'str' }
		else { 'Any' }
	}
}

// const_value_expr boxes a `@[vc_const]` literal as a Python object.
//
// The value is a literal the generator read from the source, so it is emitted as a V
// literal of the matching type: an int wide enough for any signed literal, a float, a
// bool, or a string with its inner text escaped through `vstring_literal`.
fn const_value_expr(cn Const) string {
	return match cn.kind {
		'int' { 'vcraft.to_py_int(i64(${cn.value}))' }
		'float' { 'vcraft.to_py_f64(f64(${cn.value}))' }
		'bool' { 'vcraft.to_py_bool(${cn.value})' }
		'str' { 'vcraft.to_py_string(${vstring_literal(cn.value[1..cn.value.len - 1])})' }
		else { 'vcraft.to_py_none()' }
	}
}

// render_class_exec renders a class's registration for inside `exec`.
pub fn render_class_exec(p Project, c Class) string {
	// Rendered at generation time rather than as a `for` in the output: every value
	// here is known now, and a generated `for` over the classes would need its own
	// interpolation trick for no benefit.
	mut w := new_builder()
	if c.base_index >= 0 {
		// Filled here rather than in the global's initialiser, because the base type is
		// created earlier in this same function and a global initialiser would run before
		// it exists.
		w.write_string('\tg_vc_bases_' + c.key + ' = vcraft.tuple_of_one(' +
			p.classes[c.base_index].ctype + ')\n')
	}
	w.write_string('\t' + c.ctype + ' = vcraft.new_type(')
	w.write_string(vstring_literal(c.qualified) + ',\n')
	// The state lives inside the object, so the type's `tp_basicsize` is the header plus
	// this class's state struct; the generator knows the size and passes it here.
	w.write_string('\t\tint(${c.size_fn}()),\n')
	w.write_string('\t\t' + vstring_literal(c.doc) + ',\n')
	w.write_string('\t\tvoidptr(' + c.ctor + '),\n')
	// `tp_init` is left null: the constructor runs in `tp_new`, so a subclass that
	// overrides `__init__` still gets a chance to add to it.
	w.write_string('\t\tunsafe { nil },\n')
	w.write_string('\t\tvoidptr(' + c.dealloc + '),\n')
	// Taking the address of a mutable array element needs an unsafe block, and both
	// tables are module-level globals that the type borrows for its lifetime.
	if c.methods.any(it.property == false) {
		w.write_string('\t\tunsafe { voidptr(&g_vc_methods_' + c.key + '[0]) },\n')
	} else {
		w.write_string('\t\tunsafe { nil },\n')
	}
	if c.scalar_fields().len > 0 || c.methods.any(it.property) {
		w.write_string('\t\tunsafe { voidptr(&g_vc_getsets_' + c.key + '[0]) },\n')
	} else {
		w.write_string('\t\tunsafe { nil },\n')
	}
	w.write_string('\t\tvoidptr(' + c.repr + '),\n')
	w.write_string('\t\tvoidptr(' + c.richcompare + '),\n')
	w.write_string('\t\tvoidptr(' + c.hash_fn + '),\n')
	if c.base_index < 0 {
		w.write_string('\t\tunsafe { nil },\n')
	} else {
		w.write_string('\t\tvoidptr(g_vc_bases_' + c.key + '.ptr),\n')
	}
	// `tp_traverse` and `tp_clear`, only for a class that holds references. `new_type`
	// turns them into `Py_TPFLAGS_HAVE_GC`, and that flag is what makes the collector
	// look at the instances at all: without it a cycle is never found, and the objects
	// in it are never freed.
	if c.ref_fields().len > 0 {
		w.write_string('\t\tvoidptr(vcraft_generated__traverse_' + c.key + '),\n')
		w.write_string('\t\tvoidptr(vcraft_generated__clear_' + c.key + '),\n')
	} else {
		w.write_string('\t\tunsafe { nil },\n')
		w.write_string('\t\tunsafe { nil },\n')
	}
	// `tp_iter` and `tp_iternext`, only for a class that declares the pair. The slots
	// are what make `iter()` and `next()` work; without them the methods are ordinary
	// attributes that happen to be named `iter` and `next`.
	if c.iter_fn.len > 0 {
		w.write_string('\t\tvoidptr(' + c.iter_fn + '),\n')
		w.write_string('\t\tvoidptr(' + c.next_fn + '),\n')
	} else {
		w.write_string('\t\tunsafe { nil },\n')
		w.write_string('\t\tunsafe { nil },\n')
	}
	// The buffer protocol, only for a class with a buffer field of its own. The first
	// `@[vc_buffer]` is the one `memoryview(instance)` exposes; a class that only
	// inherits one is covered by the base's slots through the type hierarchy.
	if c.own_buffer_fields().len > 0 {
		w.write_string('\t\tvoidptr(vcraft_generated__getbuffer_' + c.key + '),\n')
		w.write_string('\t\tvoidptr(vcraft_generated__releasebuffer_' + c.key + '),\n')
	} else {
		w.write_string('\t\tunsafe { nil },\n')
		w.write_string('\t\tunsafe { nil },\n')
	}
	// The sequence protocol, each slot only when the class declares it.
	for fn_ in [c.len_fn, c.item_fn, c.contains_fn] {
		if fn_.len > 0 {
			w.write_string('\t\tvoidptr(' + fn_ + '),\n')
		} else {
			w.write_string('\t\tunsafe { nil },\n')
		}
	}
	// The number protocol: the `nb_*` slots for the operators this class declares, each
	// paired with its slot id, or nothing when it declares none.
	w.write_string('\t\t' + numeric_slots_expr(c) + ',\n')
	w.write_string('\t)\n')
	// The error check is here rather than inside `new_type` because a class that fails
	// to build is a generator-level problem: the interpreter reports "raised
	// unreported exception" and nothing else, so the reason has to be surfaced while
	// there is still a name to attach it to.
	w.write_string('\tif vcraft.error_is_set() {\n')
	w.write_string('\t\teprintln(' + vstring_literal('vcraft: cannot create the type ' +
		c.name) + ')\n')
	w.write_string('\t\treturn -1\n')
	w.write_string('\t}\n')
	w.write_string('\tvcraft.add_object_ref_on(module, ' + vstring_literal(c.name) + ', ' +
		c.ctype + ')\n')
	return w.str()
}

// emit_error_raiser renders the raiser for one `@[vc_error]` type.
//
// V erases an error to `IError` by the time a wrapper sees it, so nothing but the message
// survives the trip out of a `!T` function. The exception class therefore has to be set
// *before* the value is returned, and this is the function that does it: it takes the
// user's own value, sets the pending Python exception from it, and hands back an error
// carrying the same message.
//
//	// generated
//	pub fn vcraft_generated__raise_configerror(e ConfigError) IError {
//		return vcraft.raise_custom(e.exc.ptr, e.msg())
//	}
//
// so the V side reads:
//
//	if !ok {
//		return vcraft_generated__raise_configerror(ConfigError{
//			exc: vcraft.borrow(class_ptr),
//			detail: 'no such section',
//		})
//	}
//
// A type with no `PyObj` field gets a raiser that names a builtin exception from the
// `code()` it already has, which `raise_from_error` reads on the far side:
//
//	pub fn vcraft_generated__raise_configerror(e ConfigError) IError {
//		return error(e.msg())
//	}
//
// and needs nothing at all from the generator to work: any struct with `msg()` and
// `code()` reaches Python as whatever `code()` names. The raiser exists for the type whose
// exception is not one of the builtin ones.
fn emit_error_raiser(e ErrorType) string {
	mut w := new_builder()
	w.write_string('// ---- ${e.name}\n\n')
	w.write_string('// ${e.name} is a V error type, so it can be returned from a `!T` function.\n')
	if e.doc.len > 0 {
		w.write_string('//\n')
		for line in e.doc.split('\n') {
			w.write_string('// ' + line.trim_right(' \t') + '\n')
		}
	}
	w.write_string('fn ${e.raiser}(e ${e.name}) IError {\n')
	if e.exc_field.len > 0 {
		// The exception class is borrowed from the value and CPython keeps its own
		// reference on the exception it builds, so nothing is released here.
		w.write_string('\treturn vcraft.raise_custom(e.${e.exc_field}.ptr, e.msg())\n')
	} else {
		w.write_string('\t// No `PyObj` field, so this type names a builtin exception from\n')
		w.write_string('\t// `code()` and the raiser only has to carry the message.\n')
		w.write_string('\treturn error(e.msg())\n')
	}
	w.write_string('}\n\n')
	return w.str()
}

// emit_nogil_open renders the GIL release and its guards for a `@[vc_nogil]` call.
//
// The release is paired in a `defer` rather than only on the fall-through path, because
// a panic unwinds past the explicit release. The `saved != nil` guard is what keeps that
// from double-restoring: the fall-through path restores and nulls the handle, so the
// deferred restore on the way out finds nothing to do, while a panic unwinds straight
// into a restore of the handle that is still set.
//
// The `recover` defer is registered *before* the restore defer. Defers run last in,
// first out, so the restore runs first on a panic and the raise that follows it already
// holds the GIL. Registered the other way round, the raise would run without it.
fn emit_nogil_open() string {
	mut w := new_builder()
	w.write_string('\tmut saved := vcraft.allow_threads()\n')
	w.write_string('\tdefer {\n')
	w.write_string("\t\tif message := recover() {\n")
	w.write_string('\t\t\tvcraft.raise_panic(message)\n')
	w.write_string('\t\t}\n')
	w.write_string('\t}\n')
	w.write_string('\tdefer {\n')
	w.write_string('\t\tif saved != unsafe { nil } {\n')
	w.write_string('\t\t\tvcraft.end_allow_threads(saved)\n')
	w.write_string('\t\t}\n')
	w.write_string('\t}\n')
	return w.str()
}

// emit_nogil_close renders the re-acquire after a `@[vc_nogil]` call returns.
//
// Paired with the `nil` assignment: without it the deferred restore would fire on the
// way out and restore twice, which leaves the GIL count wrong and crashes the next
// thread switch inside CPython rather than anywhere near the call that unbalanced it.
fn emit_nogil_close() string {
	return '\tvcraft.end_allow_threads(saved)\n' + '\tsaved = unsafe { nil }\n'
}

// emit_nogil_failure renders the failure path of a `@[vc_nogil]` call that returns `!T`.
//
// The error is raised here rather than captured because the GIL is re-acquired first:
// raising touches Python, and the whole point of the release is that nothing between
// the two does. The handle is nulled for the same reason as on the success path, so
// the deferred restore finds nothing to do.
fn emit_nogil_failure(inner string) string {
	return '\t\tvcraft.end_allow_threads(saved)\n' + '\t\tsaved = unsafe { nil }\n' +
		'\t\t' + inner + '\n'
}

// emit_bind_globals renders the parameter-name and optional arrays a keyword call binds
// against, once per function, at module level.
//
// As literals in the call they were a fresh heap array on every keyword or left-out-
// parameter call -- `new_array_from_c_array` in the generated C. A global is built once
// and passed as a slice, so the call allocates nothing for them.
fn emit_bind_globals(f Func) string {
	if f.params.len == 0 {
		return ''
	}
	names := f.params.map(vstring_literal(it.name)).join(', ')
	optional := f.params.map(if it.optional() { 'true' } else { 'false' }).join(', ')
	return '__global (\n' +
		'\tg_vc_names_${f.trampoline} = [${names}]\n' +
		'\tg_vc_optional_${f.trampoline} = [${optional}]\n' +
		')\n\n'
}

// emit_bind renders the argument binding at the top of a trampoline with parameters.
//
// Every parameter can be passed by position or by name, and an optional one can be left
// out. A call with keywords is bound into one slot per parameter. A positional-only call
// is not: `args` stays the raw pointer array and the readers below ask `arg_present`
// whether each index was passed, so a call that leaves out trailing parameters no longer
// builds a slot array either.
fn emit_bind(f Func) string {
	n := f.params.len
	return '\tmut args := raw_args\n' +
		'\tif kwnames != unsafe { nil } {\n' +
		'\t\tbound := []voidptr{len: ${n}, init: unsafe { nil }}\n' +
		'\t\tif !vcraft.bind_args(raw_args, nargs, kwnames, bound.data, g_vc_names_${f.trampoline}, g_vc_optional_${f.trampoline}, ${vstring_literal(f.name)}) {\n' +
		'\t\t\treturn unsafe { nil }\n\t\t}\n' + '\t\targs = bound.data\n' +
		'\t} else if int(nargs) > ${n} {\n' +
		'\t\tvcraft.reject_extra_args(${vstring_literal(f.name)}, ${n}, int(nargs))\n' +
		'\t\treturn unsafe { nil }\n\t}\n'
}

// param_reader reads one parameter, applying its default when the caller left it out.
//
// A `?T` parameter's reader already turns an absent value into `none`. A parameter with
// an `@[vc_defaults]` value starts as that value and is only read when the caller passed
// it; its reader runs inside the `if`, which is why defaults are refused for the readers
// that pin a buffer until the end of the call. A required parameter is checked present
// first, so a positional-only call that stops short is a missing-argument error rather
// than a read past the argument array.
fn param_reader(param Param, local string, index int, func string) string {
	// A `&T` parameter is an instance reference: the argument must be an instance of `T`,
	// and the function receives a pointer into that instance's state. The object read is
	// kept in `${local}_obj` so a `&T` result of the same call can be resolved back to it.
	if param.instance_target.len > 0 {
		object := '${local}_obj'
		read := '\t${object} := vcraft.require_voidptr_arg(args, ${index}, ${vstring_literal(func)}, ${vstring_literal(param.name)})\n' +
			'\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n' +
			'\t${local} := unsafe { &${param.instance_target}(vcraft.from_py_instance(${object}, ${param.instance_handle}, ${vstring_literal(param.instance_target)}, ${param.instance_offset}, ${vstring_literal(func)}, ${vstring_literal(param.name)})) }\n' +
			'\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}'
		if param.default.len == 0 && !param.optional() {
			return 'if !vcraft.arg_present(args, nargs, kwnames, ${index}) {\n' +
				'\t\tvcraft.missing_arg(${vstring_literal(func)}, ${vstring_literal(param.name)})\n' +
				'\t\treturn unsafe { nil }\n\t}\n' + read
		}
		return read
	}
	strategy := lookup(param.v_type)
	if param.default.len == 0 {
		if param.optional() {
			return reader_expr(strategy, local, index, func, param.name, param.v_type)
		}
		return 'if !vcraft.arg_present(args, nargs, kwnames, ${index}) {\n' +
			'\t\tvcraft.missing_arg(${vstring_literal(func)}, ${vstring_literal(param.name)})\n' +
			'\t\treturn unsafe { nil }\n\t}\n' +
			'\t' + reader_expr(strategy, local, index, func, param.name, param.v_type)
	}
	given := '${local}_given'
	return 'mut ${local} := ${v_default(param)}\n' +
		'\tif vcraft.arg_present(args, nargs, kwnames, ${index}) {\n' +
		'\t\t${reader_expr(strategy, given, index, func, param.name, param.v_type)}\n' +
		'\t\t${local} = ${given}\n\t}'
}

// v_default is a parameter's default as a V expression of its type.
fn v_default(param Param) string {
	t := param.v_type.trim_space()
	value := param.default.trim_space()
	if lookup(t) == .str {
		return vstring_literal(value[1..value.len - 1])
	}
	if lookup(t) == .bool {
		return value
	}
	return '${t}(${value})'
}

// python_default is a parameter's default as Python writes it, for signatures and stubs.
fn python_default(param Param) string {
	if param.default.len == 0 {
		return if param.optional() { 'None' } else { '' }
	}
	value := param.default.trim_space()
	return match value {
		'true' { 'True' }
		'false' { 'False' }
		else {
			if value[0] == `'` || value[0] == `"` {
				'"' + value[1..value.len - 1].replace('"', '\\"') + '"'
			} else {
				value
			}
		}
	}
}

// emit_method_trampoline renders a method of a class.
//
// It is the ordinary trampoline wrapped in the two statements that move the V value
// in and out of the instance's state block.
pub fn emit_method_trampoline(p Project, c Class, f Func) string {
	mut w := new_builder()
	signature := if f.params.len == 0 {
		'self voidptr, args voidptr'
	} else {
		'self voidptr, raw_args voidptr, nargs isize, kwnames voidptr'
	}
	w.write_string('fn ${f.trampoline}(${signature}) voidptr {\n')
	if f.params.len > 0 {
		w.write_string(emit_bind(f))
	}
	mut names := []string{}
	for i, param in f.params {
		name := local_name(i)
		names << name
		// A `@[vc_raw]` method reads each argument as the borrowed PyObject itself, the
		// same as a raw module function; the receiver is still the instance's state.
		if f.raw {
			w.write_string('\t${name} := vcraft.from_py_voidptr(' +
				"vcraft.require_arg(args, ${i}, '${f.name}', '${param.name}'))\n")
			w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
			continue
		}
		w.write_string('\t${param_reader(param, name, i, f.name)}\n')
	}
	w.write_string(emit_state_pointer(c))
	w.write_string(emit_enter_state(p, c))
	ret := lookup(f.v_ret)
	has_value := f.raw || ret != .void
	if has_value {
		w.write_string('\t${result_decl_of(f, ret)}\n')
	}
	if f.nogil {
		w.write_string(emit_nogil_open())
	} else {
		w.write_string('\tdefer {\n')
		w.write_string('\t\tif message := recover() {\n')
		w.write_string('\t\t\tvcraft.raise_panic(message)\n')
		w.write_string('\t\t}\n')
		w.write_string('\t}\n')
	}
	call := if f.params.len == 0 { 'state.' + c.self_access() + '${f.name}()' } else { 'state.' + c.self_access() + '${f.name}(${names.join(', ')})' }
	if f.returns_result {
		inner := 'vcraft.raise_from_error(err)\n\t\treturn unsafe { nil }'
		if has_value {
			// Assigned, not declared: `mut result` was emitted above when the method
			// returns a value, and `:=` here redefines it, which V rejects outright.
			if f.nogil {
				w.write_string('\t${result_target(ret, f.v_ret)} = ${call} or {\n' + emit_nogil_failure(inner) +
					'\t}\n')
			} else {
				w.write_string('\t${result_target(ret, f.v_ret)} = ${call} or {\n\t\t${inner}\n\t}\n')
			}
		} else {
			if f.nogil {
				w.write_string('\t${call} or {\n' + emit_nogil_failure(inner) + '\t}\n')
			} else {
				w.write_string('\t${call} or {\n\t\t${inner}\n\t}\n')
			}
		}
		// Re-acquired before the state is written back and the error is checked: the
		// check touches Python, and without the GIL it races the next thread switch.
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
	} else if has_value {
		w.write_string('\t${result_target(ret, f.v_ret)} = ${call}\n')
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
	} else {
		w.write_string('\t${call}\n')
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
	}
	// The instance is written back before anything can fail, so a method that
	// raises leaves the object consistent.
	w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
	if has_value {
		w.write_string(emit_tail_return(f, ret, instance_candidates(f, true), f.raw))
	} else {
		w.write_string('\treturn vcraft.to_py_none().ptr\n')
	}
	w.write_string('}\n')
	return w.str()
}

// emit_static_trampoline renders a `@[vc_static]` method.
//
// It is the module-function trampoline with the call target spelled `Receiver.name`. A
// static method takes no receiver, so CPython passes NULL as `self` and nothing here
// touches an instance: no state pointer, no published chain. The Python name is the
// method's own; only the V call carries the receiver.
pub fn emit_static_trampoline(f Func) string {
	mut w := new_builder()
	signature := if f.params.len == 0 {
		'self voidptr, args voidptr'
	} else {
		'self voidptr, raw_args voidptr, nargs isize, kwnames voidptr'
	}
	w.write_string('fn ${f.trampoline}(${signature}) voidptr {\n')
	if f.params.len > 0 {
		w.write_string(emit_bind(f))
	}
	mut names := []string{}
	for i, param in f.params {
		name := local_name(i)
		names << name
		w.write_string('\t${param_reader(param, name, i, f.name)}\n')
	}
	ret := lookup(f.v_ret)
	has_value := ret != .void
	if has_value {
		w.write_string('\t${result_decl_of(f, ret)}\n')
	}
	if f.nogil {
		w.write_string(emit_nogil_open())
	} else {
		w.write_string('\tdefer {\n')
		w.write_string('\t\tif message := recover() {\n')
		w.write_string('\t\t\tvcraft.raise_panic(message)\n')
		w.write_string('\t\t}\n')
		w.write_string('\t}\n')
	}
	call := '${f.static_receiver}.${f.name}(${names.join(', ')})'
	if f.returns_result {
		inner := 'vcraft.raise_from_error(err)\n\t\treturn unsafe { nil }'
		if has_value {
			if f.nogil {
				w.write_string('\t${result_target(ret, f.v_ret)} = ${call} or {\n' + emit_nogil_failure(inner) +
					'\t}\n')
			} else {
				w.write_string('\t${result_target(ret, f.v_ret)} = ${call} or {\n\t\t${inner}\n\t}\n')
			}
		} else {
			if f.nogil {
				w.write_string('\t${call} or {\n' + emit_nogil_failure(inner) + '\t}\n')
			} else {
				w.write_string('\t${call} or {\n\t\t${inner}\n\t}\n')
			}
		}
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
	} else {
		if has_value {
			w.write_string('\t${result_target(ret, f.v_ret)} = ${call}\n')
		} else {
			w.write_string('\t${call}\n')
		}
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
	}
	w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
	if has_value {
		w.write_string(emit_tail_return(f, ret, instance_candidates(f, false), false))
	} else {
		w.write_string('\treturn vcraft.to_py_none().ptr\n')
	}
	w.write_string('}\n')
	return w.str()
}

// emit_property_trampoline renders a method exposed as a Python property.
//
// A getter is called with the instance and the descriptor closure, not with an
// argument tuple, and it must take no arguments.
pub fn emit_property_trampoline(p Project, c Class, f Func) string {
	mut w := new_builder()
	w.write_string('fn ${f.trampoline}(self voidptr, closure voidptr) voidptr {\n')
	w.write_string(emit_state_pointer(c))
	w.write_string(emit_enter_state(p, c))
	ret := lookup(f.v_ret)
	if f.nogil {
		w.write_string(emit_nogil_open())
	} else {
		w.write_string('\tdefer {\n')
		w.write_string('\t\tif message := recover() {\n')
		w.write_string('\t\t\tvcraft.raise_panic(message)\n')
		w.write_string('\t\t}\n')
		w.write_string('\t}\n')
	}
	if ret != .void {
		// A property getter declares its own `result`. It has no argument tuple, so it
		// does not go through the path that declares one for a method, and without this
		// the return statement at the end refers to a variable that was never declared.
		w.write_string('\t${result_decl_of(f, ret)}\n')
	}
	if f.returns_result {
		inner := 'vcraft.raise_from_error(err)\n\treturn unsafe { nil }'
		// Assigned, not declared: `mut result` is emitted above when the method returns
		// a value, and `:=` here would shadow it -- or rather, redefine it, which V
		// rejects outright.
		if f.nogil {
			w.write_string('\t${result_target(ret, f.v_ret)} = state.' + c.self_access() +
				'${f.name}() or {\n' + emit_nogil_failure(inner) + '\t}\n')
		} else {
			w.write_string('\t${result_target(ret, f.v_ret)} = state.' + c.self_access() + '${f.name}() or {\n\t${inner}\n\t}\n')
		}
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
		w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
		w.write_string(emit_tail_return(f, ret, instance_candidates(f, true), false))
	} else if ret != .void {
		// A plain getter: the call is assigned to the `result` declared above. Without
		// this the value is computed and dropped on the floor, and the getter returns the
		// zero value it was initialised with.
		w.write_string('\t${result_target(ret, f.v_ret)} = state.' + c.self_access() + '${f.name}()\n')
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
		w.write_string(emit_tail_return(f, ret, instance_candidates(f, true), false))
	} else {
		// A property returning nothing has no `result` to assign: it was never declared,
		// and assigning to it is a compile error rather than a warning.
		w.write_string('\tstate.' + c.self_access() + '${f.name}()\n')
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
		w.write_string(emit_tail_return(f, ret, instance_candidates(f, true), false))
	}
	w.write_string('}\n')
	return w.str()
}

// module_docstring is the module's `__doc__`, taken from the first exported
// function's doc comment since a project has no module-level one of its own.
fn module_docstring(p Project) string {
	for f in p.funcs {
		if f.doc.len > 0 {
			return f.doc.split('\n')[0]
		}
	}
	return '${p.package}, built with vcraft.'
}

// local_name is the generated name for the i-th argument. It is positional rather
// than taken from the V parameter so that two parameters of the same type cannot
// collide, which is what a naive `v :=` per parameter would do.
fn local_name(i int) string {
	return 'arg${i}'
}

// emit_trampoline renders one trampoline.
pub fn emit_trampoline(f Func) string {
	mut w := new_builder()
	signature := if f.params.len == 0 {
		'self voidptr, args voidptr'
	} else {
		'self voidptr, raw_args voidptr, nargs isize, kwnames voidptr'
	}
	w.write_string('fn ${f.trampoline}(${signature}) voidptr {\n')

	if f.params.len > 0 {
		w.write_string(emit_bind(f))
	}

	// `@[vc_raw]` keeps the declared signature but skips every conversion: each
	// parameter is handed over as the borrowed `PyObject *` itself, and the result
	// is returned as whatever pointer the function produced. The V function owns
	// every reference it touches.
	mut names := []string{}
	for i, param in f.params {
		if f.raw {
			name := local_name(i)
			names << name
			w.write_string('\t${name} := vcraft.from_py_voidptr(' +
				"vcraft.require_arg(args, ${i}, '${f.name}', '${param.name}'))\n")
			w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
			continue
		}
		name := local_name(i)
		names << name
		w.write_string('\t${param_reader(param, name, i, f.name)}\n')
	}


	ret := lookup(f.v_ret)
	has_value := f.raw || ret != .void

	// The result is declared before the guard so that the call has somewhere to assign
	// even when the guard unwinds past it. Declared for a `!T` function too: the call
	// below assigns to it rather than introducing it with `:=`, because `:=` on an
	// existing name is a redefinition and V rejects that outright.
	if has_value {
		w.write_string('\t${result_decl_of(f, ret)}\n')
	}
	// A raw function's result is a borrowed pointer, so `return_expr` takes a reference
	// of its own on it before CPython receives it; the V side does not own the caller's
	// reference.
	//
	// `@[vc_nogil]` replaces the guard with the release and its own pair of guards: the
	// recover defer first so it runs last, already holding the GIL, and the restore
	// defer second so it runs first. Everything between them runs without the GIL and
	// must not touch Python.
	if f.nogil {
		w.write_string(emit_nogil_open())
	} else {
		w.write_string('\tdefer {\n')
		w.write_string('\t\tif message := recover() {\n')
		w.write_string('\t\t\tvcraft.raise_panic(message)\n')
		w.write_string('\t\t}\n')
		w.write_string('\t}\n')
	}

	call := if f.params.len == 0 { '${f.name}()' } else { '${f.name}(${names.join(', ')})' }

	if f.returns_result {
		// V has no `is` test for a Result, so error propagation is the mechanism:
		// the `or` block receives `err` directly and turns it into a Python
		// exception before returning.
		inner := 'vcraft.raise_from_error(err)\n\t\treturn unsafe { nil }'
		if has_value {
			// Assigned, not declared: `mut result` was emitted above when the method
			// returns a value, and `:=` here redefines it, which V rejects outright.
			if f.nogil {
				w.write_string('\t${result_target(ret, f.v_ret)} = ${call} or {\n' + emit_nogil_failure(inner) +
					'\t}\n')
			} else {
				w.write_string('\t${result_target(ret, f.v_ret)} = ${call} or {\n\t\t${inner}\n\t}\n')
			}
		} else {
			if f.nogil {
				w.write_string('\t${call} or {\n' + emit_nogil_failure(inner) + '\t}\n')
			} else {
				w.write_string('\t${call} or {\n\t\t${inner}\n\t}\n')
			}
		}
		// The success path re-acquires here rather than in the deferred restore: everything
		// below touches Python (`error_is_set`, boxing the result), and running any of it
		// without the GIL races the next thread switch and dies inside `PyErr_Occurred`
		// with nothing in the frame pointing back at the missing re-acquire.
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
		w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
	} else {
		if has_value {
			w.write_string('\t${result_target(ret, f.v_ret)} = ${call}\n')
		} else {
			w.write_string('\t${call}\n')
		}
		if f.nogil {
			w.write_string(emit_nogil_close())
		}
		w.write_string('\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}\n')
		if has_value {
			w.write_string(emit_tail_return(f, ret, instance_candidates(f, false), f.raw))
		} else {
			w.write_string('\treturn vcraft.to_py_none().ptr\n')
		}
		w.write_string('}\n')
		return w.str()
	}

	w.write_string(emit_tail_return(f, ret, instance_candidates(f, false), f.raw))
	w.write_string('}\n')
	return w.str()
}

// return_expr is the final `return` of a trampoline.
//
// A raw result is a `voidptr` handed over borrowed, so a reference of the caller's own
// is taken on it. Everything else is a real V value that has to be boxed. `v_type` is
// the declared value type, which a sequence needs to choose how each element is boxed.
pub fn return_expr(strategy Strategy, value string, raw bool, v_type string, export_buffer bool) string {
	if raw {
		// A raw function hands back a borrowed pointer, so the wrapper takes the
		// reference itself. Without this the caller receives a pointer it never
		// owned and CPython over-decrements it at teardown, which crashes the
		// interpreter on exit rather than at the call.
		return "vcraft.borrow(${value}).new_ref().ptr"
	}
	if export_buffer {
		// A `@[vc_memoryview]` result: hand the native-backed slice to CPython as a
		// writable `memoryview`, transferring ownership of its backing. Nothing is
		// boxed, so the element's format family is all the runtime needs.
		return 'vcraft.buffer_export_${element_type(v_type)}(${value}).ptr'
	}
	// `boxed_expr` already produces an expression that yields the object, except for
	// `.pyref`, where it is the object itself rather than a pointer to one.
	return match strategy {
		.pyref { boxed_expr(strategy, value) + '.ptr' }
		// A `voidptr` result is borrowed, the same contract as a raw one, and it is
		// already a pointer: boxing it and taking `.ptr` does not compile.
		.pyobj { 'vcraft.borrow(${value}).new_ref().ptr' }
		.seq { '${seq_boxed_expr(element_type(v_type), value)}.ptr' }
		// A multi-value result lives in `result0`, `result1`...: see `result_decl`.
		.tuple {
			parts := tuple_parts(v_type)
			items := []string{len: parts.len, init: boxed_expr(lookup(parts[index]), 'result${index}')}
			'vcraft.tuple_of([${items.join(', ')}]).ptr'
		}
		.optional, .dict, .fixed { '${composite_boxed_expr(strategy, value, v_type)}.ptr' }
		else { '${boxed_expr(strategy, value)}.ptr' }
	}
}

// instance_candidates is the V expression for the list of instances a `&T` result could
// point into: the receiver when there is one, then the object read for each `&T`
// parameter. It is the set the runtime matches the returned pointer against.
fn instance_candidates(f Func, with_self bool) string {
	mut parts := []string{}
	if with_self {
		parts << 'voidptr(self)'
	}
	for i, param in f.params {
		if param.instance_target.len > 0 {
			parts << 'voidptr(${local_name(i)}_obj)'
		}
	}
	if parts.len == 0 {
		return '[]voidptr{}'
	}
	return '[${parts.join(', ')}]'
}

// instance_result_expr hands Python the instance a `&T` result points into, resolved from
// the candidates of the call. It yields the object pointer, which is what a trampoline
// returns.
fn instance_result_expr(f Func, value string, candidates string) string {
	return 'vcraft.instance_ref(voidptr(${value}), ${f.instance_result_handle}, ${vstring_literal(f.instance_result)}, ${f.instance_result_offset}, ${candidates}, ${vstring_literal(f.name)})'
}

// emit_tail_return is the final `return` of a trampoline, instance reference or not.
fn emit_tail_return(f Func, ret Strategy, candidates string, raw bool) string {
	if f.instance_result.len > 0 {
		return '\treturn ${instance_result_expr(f, 'result', candidates)}\n'
	}
	return '\treturn ${return_expr(ret, 'result', raw, f.v_ret, f.export_buffer)}\n'
}

// composite_boxed_expr boxes an optional, a map or a fixed-size array as an expression.
//
// The map is boxed by an immediately called function literal, because building a
// `dict` takes a loop and every caller of this needs a single expression.
fn composite_boxed_expr(strategy Strategy, value string, v_type string) string {
	t := v_type.trim_space()
	return match strategy {
		.optional {
			inner := t[1..]
			'(if opt_value := ${value} { ${box_value_expr('opt_value', inner)} } else { vcraft.to_py_none() })'
		}
		.dict {
			key, val := map_parts(t)
			'vcraft.to_py_dict(${value}, fn (k ${key}) vcraft.PyObj { return ${box_value_expr('k', key)} }, fn (v ${val}) vcraft.PyObj { return ${box_value_expr('v', val)} })'
		}
		.fixed { seq_boxed_expr(fixed_element(t), '${value}[..]') }
		else { boxed_expr(strategy, value) }
	}
}

// box_value_expr boxes a V value of the declared type as a Python object expression.
//
// It is the recursive entry point: a container boxes each element by calling it again, so
// `map[string][]int` and `[][]int` work. `boxed_expr` is the leaf for the scalar types and
// is what every non-composite case still calls.
pub fn box_value_expr(value string, v_type string) string {
	return match lookup(v_type) {
		.seq { seq_boxed_expr(element_type(v_type), value) }
		.optional, .dict, .fixed { composite_boxed_expr(lookup(v_type), value, v_type) }
		else { boxed_expr(lookup(v_type), value) }
	}
}

// result_decl_of declares the local a trampoline assigns the call's result to, with the
// pointer type a `&T` result needs: an instance reference is a typed pointer, not the
// null `voidptr` the generic zero value would give it.
fn result_decl_of(f Func, strategy Strategy) string {
	if f.instance_result.len > 0 {
		return 'mut result := unsafe { &${f.instance_result}(nil) }'
	}
	return result_decl(strategy, f.v_ret)
}

// result_decl declares the local a trampoline assigns the call's result to: `result`,
// or `result0`, `result1`... for a multi-value return, which V can only destructure.
pub fn result_decl(strategy Strategy, v_type string) string {
	if strategy == .tuple {
		parts := tuple_parts(v_type)
		mut lines := []string{}
		for i, part in parts {
			lines << 'mut result${i} := ${zero_value(lookup(part), part)}'
		}
		return lines.join('\n\t')
	}
	return 'mut result := ${zero_value(strategy, v_type)}'
}

// result_target is the left-hand side the call is assigned to.
pub fn result_target(strategy Strategy, v_type string) string {
	if strategy == .tuple {
		return []string{len: tuple_parts(v_type).len, init: 'result${index}'}.join(', ')
	}
	return 'result'
}

// seq_boxed_expr boxes a returned `[]T` as a list. Slices of the plain number types
// the runtime has a one-pass builder for use it; every other element type goes through
// `to_py_list` with a boxing rule.
fn seq_boxed_expr(element string, value string) string {
	return match element {
		'i64' { 'vcraft.to_py_i64_list(${value})' }
		'int' { 'vcraft.to_py_int_list(${value})' }
		'f64' { 'vcraft.to_py_f64_list(${value})' }
		else { 'vcraft.to_py_list(${value}, ${element_box_fn(element)})' }
	}
}

// element_box_fn renders the boxing rule `vcraft.to_py_list` applies to each element
// of a returned `[]T`, as an anonymous function from `T` to an object.
//
// The runtime cannot pick the rule itself: the element type is only known here. Each
// rule widens to the one width its boxer takes, so every integer width shares
// `to_py_int`. An element with no rule is refused by `validate` before this runs.
pub fn element_box_fn(element string) string {
	boxed := match lookup(element) {
		.int { 'vcraft.to_py_int(i64(x))' }
		.uint { 'vcraft.to_py_uint(u64(x))' }
		.float { 'vcraft.to_py_f64(f64(x))' }
		.str { 'vcraft.to_py_string(x)' }
		.bool { 'vcraft.to_py_bool(x)' }
		.complex { 'vcraft.to_py_complex(x)' }
		.bytes { 'vcraft.to_py_bytes_slice(x)' }
		.seq { seq_boxed_expr(element_type(element), 'x') }
		.optional, .dict, .fixed { composite_boxed_expr(lookup(element), 'x', element) }
		else { 'vcraft.to_py_none()' }
	}
	return 'fn (x ${element}) vcraft.PyObj { return ${boxed} }'
}

// element_is_boxable reports whether a returned `[]T` has an element rule.
pub fn element_is_boxable(element string) bool {
	return is_element_type(element)
}

// is_boxable_type reports whether a declared type can be boxed, recursively: a scalar, a
// container whose elements are boxable, or nothing. A multi-value type is boxable when
// each part is; a bare object and a void are not.
pub fn is_boxable_type(v_type string) bool {
	t := v_type.trim_space()
	return match lookup(t) {
		.seq { is_boxable_type(element_type(t)) }
		.optional { is_boxable_type(t[1..]) }
		.dict {
			key, val := map_parts(t)
			lookup(key) in [.bool, .int, .uint, .float, .str] && is_boxable_type(val)
		}
		.fixed { is_boxable_type(fixed_element(t)) }
		.tuple { tuple_parts(t).all(is_boxable_type(it)) }
		// A void result and a bare object are boxed by `return_expr`; anything the type
		// table does not know has no rule.
		.unsupported { false }
		else { true }
	}
}

// element_is_readable reports whether a `[]T` parameter has an element reader.
//
// `[]u8` never reaches this: it is a buffer, read through the buffer protocol
// rather than as a sequence.
pub fn element_is_readable(element string) bool {
	if element == 'u8' {
		return false
	}
	return lookup(element) in [.int, .uint, .float, .str, .bool]
}

// zero_value is the initial value of a result local. It has to be valid V for the
// declared type, which rules out `T(0)` for strings and slices. A uint result
// starts as `u64(0)` rather than `0`: the local is assigned the declared width
// before it is boxed, and `to_py_uint` takes nothing narrower.
pub fn zero_value(strategy Strategy, v_type string) string {
	return match strategy {
		.void { 'unsafe { nil }' }
		.bool { 'false' }
		.int { '0' }
		.uint { 'u64(0)' }
		.float { '0.0' }
		.str { "''" }
		// `.bytes` is always a `[]u8`: a string literal would not compile where a slice
		// is declared.
		.bytes { '[]u8{}' }
		.pyref { 'vcraft.null' }
		.seq { '${v_type}{}' }
		.optional { '${v_type.trim_space()}(none)' }
		.dict, .fixed { '${v_type.trim_space()}{}' }
		// A call rather than a literal, so generated code never has to name
		// `complex.Complex` and the glue needs no `math.complex` import.
		.complex { 'vcraft.zero_complex()' }
		// Never declared as one local: `result_decl` declares one per element.
		.tuple { 'unsafe { nil }' }
		.pyobj, .unsupported { 'unsafe { nil }' }
	}
}

// scalar_narrower names the runtime converter for a scalar narrower than the width its
// strategy reads (`int`, `u64`, `f64`), or returns '' when the plain reader fits.
fn scalar_narrower(v_type string) string {
	return match v_type {
		'i8' { 'i8_from_py_int' }
		'i16' { 'i16_from_py_int' }
		'i32' { 'i32_from_py_int' }
		'rune' { 'rune_from_py_int' }
		'u8' { 'u8_from_py_uint' }
		'u16' { 'u16_from_py_uint' }
		'u32' { 'u32_from_py_uint' }
		'f32' { 'f32_from_py_f64' }
		else { '' }
	}
}

// reader_expr returns the statement that reads positional argument `index` into the
// local `local`, with the V type a Python value maps onto.
//
// Every converting branch ends in `or { return unsafe { nil } }`, because the reader
// raises the Python exception itself and the trampoline only has to notice that
// something is pending.
pub fn reader_expr(strategy Strategy, local string, index int, func string, param string,
	param_type string) string {
	// A width narrower than the reader's result does not convert implicitly in V:
	// `i8`, `i16`, `i32`, `u8`, `u16`, `u32` and `f32` parameters generated glue that
	// did not compile. They read the object and go through the same range-checked
	// narrower their sequences use, so an out-of-range value raises OverflowError.
	if strategy in [.optional, .dict, .fixed, .tuple] {
		return composite_reader(strategy, local, index, func, param, param_type)
	}
	narrower := scalar_narrower(param_type.trim_space())
	call := match strategy {
		.bool { "vcraft.from_py_bool_arg(args, ${index}, '${func}', '${param}')" }
		.int, .uint, .float {
			if narrower.len > 0 {
				"vcraft.${narrower}(vcraft.required_arg(args, ${index}, '${func}', '${param}') or { return unsafe { nil } }, '${param}')"
			} else if strategy == .int {
				"vcraft.from_py_int_arg(args, ${index}, '${func}', '${param}')"
			} else if strategy == .uint {
				"vcraft.from_py_uint_arg(args, ${index}, '${func}', '${param}')"
			} else {
				"vcraft.from_py_f64_arg(args, ${index}, '${func}', '${param}')"
			}
		}
		.str { "vcraft.from_py_string_arg(args, ${index}, '${func}', '${param}')" }
		// A `[]u8` parameter takes any bytes-like object without copying it. Exact
		// `bytes` aliases the object with no view at all; anything else goes
		// through a view whose deferred release pins the exporter for the call.
		// The slice must not outlive the call, because the release drops the
		// exporter's reference.
		.bytes {
			"\t${local}_bytes := vcraft.bytes_arg(args, ${index}, '${func}', '${param}') or { return unsafe { nil } }\n" +
				'\tdefer { ${local}_bytes.release() }\n' +
				'\t${local} := ${local}_bytes.data'
		}
		.seq {
			element := element_type(param_type)
			match lookup(element) {
				// An `i64` element has its own reader: V does not convert a `[]int` into
				// a `[]i64`, so the int reader's result does not compile there. The
				// narrower widths have theirs for the same reason; only `int` itself
				// uses the one-pass C reader.
				.int {
					if element == 'i64' {
						"vcraft.from_py_i64_seq_arg(args, ${index}, '${func}', '${param}')"
					} else if element == 'int' {
						"vcraft.from_py_int_seq_arg(args, ${index}, '${func}', '${param}')"
					} else {
						"vcraft.from_py_${element}_seq_arg(args, ${index}, '${func}', '${param}')"
					}
				}
				.uint {
					if element == 'u64' {
						"vcraft.from_py_uint_seq_arg(args, ${index}, '${func}', '${param}')"
					} else {
						"vcraft.from_py_${element}_seq_arg(args, ${index}, '${func}', '${param}')"
					}
				}
				.float {
					if element == 'f64' {
						"vcraft.from_py_f64_seq_arg(args, ${index}, '${func}', '${param}')"
					} else {
						"vcraft.from_py_${element}_seq_arg(args, ${index}, '${func}', '${param}')"
					}
				}
				.str { "vcraft.from_py_str_seq_arg(args, ${index}, '${func}', '${param}')" }
				.bool { "vcraft.from_py_bool_seq_arg(args, ${index}, '${func}', '${param}')" }
				else { "vcraft.from_py_int_seq_arg(args, ${index}, '${func}', '${param}')" }
			}
		}
		.pyobj {
			// A `voidptr` parameter, so the reader hands one over. `require_arg` returns a
			// `PyObj` and relies on V dereferencing the struct into the `voidptr`, which
			// warns and is documented as going away.
			"\t${local} := vcraft.require_voidptr_arg(args, ${index}, '${func}', '${param}')\n" +
				'\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}'
		}
		.complex {
			"vcraft.from_py_complex(vcraft.required_arg(args, ${index}, '${func}', '${param}') or { return unsafe { nil } }, '${param}')"
		}
		else {
			"\t${local} := vcraft.require_arg(args, ${index}, '${func}', '${param}')\n" +
				'\tif vcraft.error_is_set() {\n\t\treturn unsafe { nil }\n\t}'
		}
	}
	// `.bytes` renders its own statements -- acquire, deferred release, alias -- so
	// like the other multi-line readers it is returned whole rather than wrapped in an
	// assignment it already contains.
	if strategy == .pyobj || strategy == .pyref || strategy == .bytes || strategy == .unsupported {
		return call
	}
	return '${local} := ${call} or { return unsafe { nil } }'
}

// python_signature renders `name(a: int, b: int) -> int` for `__text_signature__`.
pub fn python_signature(f Func) string {
	return '${f.name}(${param_list(f)}) -> ${result_annotation(f)}'
}

// result_annotation is the Python type name for a function's result. A
// `@[vc_memoryview]` result is a `memoryview` whatever the V slice's element type, so it
// does not go through `describe`.
pub fn result_annotation(f Func) string {
	if f.export_buffer {
		return 'memoryview'
	}
	return describe(f.v_ret)
}

fn param_list(f Func) string {
	mut parts := []string{}
	for param in f.params {
		default := python_default(param)
		parts << '${param.name}: ${describe(param.v_type)}' + if default.len > 0 { ' = ${default}' } else { '' }
	}
	return parts.join(', ')
}

// boxed_expr returns the expression that boxes a V value as a Python object.
pub fn boxed_expr(strategy Strategy, value string) string {
	return match strategy {
		.void { 'vcraft.to_py_none()' }
		.bool { 'vcraft.to_py_bool(' + value + ')' }
		.int { 'vcraft.to_py_int(' + value + ')' }
		.uint { 'vcraft.to_py_uint(' + value + ')' }
		.float { 'vcraft.to_py_f64(' + value + ')' }
		.str { 'vcraft.to_py_string(' + value + ')' }
		// A V `math.complex.Complex` becomes a Python `complex`.
		.complex { 'vcraft.to_py_complex(' + value + ')' }
		// Copying: a Python `bytes` owns immutable storage, so there is nothing to
		// alias a V slice into. Reads cost nothing; writes pay for the type.
		.bytes { 'vcraft.to_py_bytes_slice(' + value + ')' }
		.seq { 'vcraft.to_py_list(' + value + ')' }
		// Boxed through `composite_boxed_expr`, which needs the declared type; fields of
		// these types are refused before glue is written.
		.optional, .dict, .tuple, .fixed { 'vcraft.to_py_none()' }
		.pyobj { value }
		// The V value owns a reference and CPython steals the one a getter returns, so
		// the ownership moves rather than being copied. `steal` is the spelling of that.
		.pyref { 'vcraft.steal(' + value + '.ptr)' }
		.unsupported { 'unsafe { nil }' }
	}
}

// unbox_expr renders the call that converts an incoming `PyObject *` into the V type
// a field holds. A setter cannot copy the bytes: the object behind an int is a
// `PyLong` with CPython's own layout.
pub fn unbox_expr(strategy Strategy, value string, v_type string) string {
	// A narrow field is converted to its own width, range-checked. Unboxing it at the
	// strategy's width and then copying `sizeof(field)` bytes of that wider local wrote
	// the low bytes of an `f64` into an `f32` field (garbage) and truncated an
	// out-of-range `i8` without a word.
	narrower := scalar_narrower(v_type.trim_space())
	if narrower.len > 0 && strategy in [.int, .uint, .float] {
		return 'vcraft.${narrower}(vcraft.borrow(' + value + '), ' + vstring_literal('value') + ')'
	}
	return match strategy {
		.bool { 'vcraft.unbox_bool(' + value + ')' }
		.int { 'vcraft.unbox_int(' + value + ', ' + vstring_literal('value') + ')' }
		.uint { 'vcraft.unbox_uint(' + value + ', ' + vstring_literal('value') + ')' }
		.float { 'vcraft.unbox_f64(' + value + ', ' + vstring_literal('value') + ')' }
		.complex { 'vcraft.from_py_complex(vcraft.borrow(' + value + '), ' + vstring_literal('value') + ')' }
		// Borrowed, because the caller keeps its own reference to whatever it passed.
		// The value it ends up in is released with `decref` or handed to a field, which
		// counts it.
		.pyref { 'vcraft.borrow(' + value + ')' }
		else { 'vcraft.unbox_int(' + value + ', ' + vstring_literal('value') + ')' }
	}
}

// py_repr_expr renders a V expression that produces the Python repr of a value.
pub fn py_repr_expr(strategy Strategy, value string) string {
	return match strategy {
		.bool { 'vcraft.repr_bool(' + value + ')' }
		.int { 'vcraft.repr_int(' + value + ')' }
		.uint { 'vcraft.repr_uint(' + value + ')' }
		.float { 'vcraft.repr_f64(' + value + ')' }
		.str { 'vcraft.repr_string(' + value + ')' }
		else { "'...'" }
	}
}

// The bytes that have to be escaped inside a single-quoted V literal.
const esc_backslash = u8(92)

const esc_quote = u8(39)

const esc_newline = u8(10)

const esc_return = u8(13)

const esc_tab = u8(9)

// vstring_literal renders a V string literal, escaping what V needs escaped.
//
// A docstring arrives from the user's source as plain text and may hold a quote, a
// backslash or a newline, any of which would otherwise end the literal early.
pub fn vstring_literal(text string) string {
	mut w := new_builder()
	w.write_string("'")
	for ch in text {
		if ch == esc_backslash {
			w.write_string('\\\\')
		} else if ch == esc_quote {
			w.write_string("\\'")
		} else if ch == esc_newline {
			w.write_string('\\n')
		} else if ch == esc_return {
			w.write_string('\\r')
		} else if ch == esc_tab {
			w.write_string('\\t')
		} else {
			w.write_u8(ch)
		}
	}
	w.write_string("'")
	return w.str()
}

// emit_stubs renders the `.pyi` type stub for a project.
pub fn emit_stubs(p Project) string {
	mut w := new_builder()
	w.write_string('# Generated by vcraft. Do not edit.\n')
	w.write_string('# Regenerate with `vcraft build`.\n\n')
	w.write_string('from typing import Any, Sequence\n')
	// Module-level constants, declared with their Python type so a type checker sees them.
	for cn in p.consts {
		w.write_string('${cn.name}: ${const_stub_type(cn.kind)}\n')
	}
	for f in p.funcs {
		w.write_string('\n')
		if f.doc.len > 0 {
			w.write_string('${indent_doc(f.doc)}\n')
		}
		w.write_string('def ${f.name}(${param_list(f)}) -> ${result_annotation(f)}: ...\n')
	}
	for c in p.classes {
		w.write_string('\n')
		if c.doc.len > 0 {
			w.write_string('${indent_doc(c.doc)}\n')
		}
		// The base is in the declaration because it is in the type: a stub that said
		// `class BoundedCounter:` would type-check `b.value` as an error, since the stub
		// has no base to inherit the field from.
		if c.base_index >= 0 {
			w.write_string('class ${c.name}(${c.base}):\n')
		} else {
			w.write_string('class ${c.name}:\n')
		}
		// Fields come first and are attributes rather than methods: that is what they
		// are at runtime, and a stub that declared them as methods would type-check
		// `c.value` as a bound method. Only this class's own fields: the stub's base
		// declaration already accounts for the inherited ones.
		for field in c.scalar_fields() {
			w.write_string('    ${field.name}: ${describe(field.v_type)}\n')
		}
		// A native buffer is not an attribute, so it has no field line; it is reachable
		// through `memoryview(instance)` and through methods.
		// A subclass with no constructor of its own still takes Python arguments when its
		// base does: `tp_new` binds the base's parameters and `newstate` forwards them.
		// The signature has to say so, or a type checker rejects a call that works.
		if c.ctor_fn.len > 0 || c.newstate_params.len > 0 {
			w.write_string('    def __init__(self${c.stub_ctor_params()}) -> None: ...\n')
		}
		for method in c.methods {
			if method.property {
				w.write_string('    @property\n')
			}
			if method.static || method.classmethod {
				w.write_string(if method.classmethod { '    @classmethod\n' } else { '    @staticmethod\n' })
				args := method_params(method).all_after(', ').trim_space()
				w.write_string('    def ${method.name}(${args}) -> ${result_annotation(method)}: ...\n')
				continue
			}
			w.write_string('    def ${method.name}(self${method_params(method)}) -> ' +
				'${result_annotation(method)}: ...\n')
		}
	}
	return w.str()
}

fn method_params(f Func) string {
	if f.params.len == 0 {
		return ''
	}
	return ', ' + param_list(f)
}

// indent_doc re-indents a doc comment as a Python docstring.
fn indent_doc(doc string) string {
	lines := doc.split('\n')
	if lines.len == 1 {
		return '"""${lines[0]}"""'
	}
	mut out := '"""${lines[0]}\n'
	for line in lines[1..] {
		// No trailing whitespace on empty lines: a `\t` alone is invisible in the
		// file, breaks `git diff --check`, and says nothing to a reader.
		out += if line.len > 0 { '\t${line}' } else { '' }
		out += '\n'
	}
	return out + '"""'
}

// element_type returns the element type of a `[]T`, which decides which sequence
// reader the generated code calls.
pub fn element_type(v_type string) string {
	base := v_type.trim_space()
	return if base.starts_with('[]') { base[2..] } else { base }
}

// value_from_obj converts one borrowed object to a plain V value of `v_type`, as an
// expression that returns from the trampoline when the conversion raises.
fn value_from_obj(v_type string, obj string, param string) string {
	t := v_type.trim_space()
	name := vstring_literal(param)
	fail := ' or { return unsafe { nil } }'
	narrower := scalar_narrower(t)
	if narrower.len > 0 {
		return 'vcraft.${narrower}(${obj}, ${name})${fail}'
	}
	return match lookup(t) {
		.bool { 'vcraft.from_py_bool(${obj})' }
		.int { '${t}(vcraft.from_py_int(${obj}, ${name})${fail})' }
		.uint { '${t}(vcraft.from_py_uint(${obj}, ${name})${fail})' }
		.float { '${t}(vcraft.from_py_f64(${obj}, ${name})${fail})' }
		.str { 'vcraft.from_py_string(${obj}, ${name})${fail}' }
		else { 'unsafe { nil }' }
	}
}

// composite_reader reads an optional, a map or a fixed-size array parameter.
fn composite_reader(strategy Strategy, local string, index int, func string, param string,
	param_type string) string {
	t := param_type.trim_space()
	obj := '${local}_obj'
	fetch := "${obj} := vcraft.required_arg(args, ${index}, '${func}', '${param}') or { return unsafe { nil } }"
	return match strategy {
		// Left out or None is `none`; anything else must convert like the plain
		// parameter would.
		.optional {
			// A `?T` parameter may be left out, so the read is guarded: a positional-only
			// call has no slot array and index `i` may be past the argument array.
			'${obj} := if vcraft.arg_present(args, nargs, kwnames, ${index}) { vcraft.arg_at(args, ${index}) } else { vcraft.PyObj{} }\n' +
				'\tmut ${local} := ${t}(none)\n' +
				'\tif !${obj}.is_null() && !vcraft.is_none_ptr(${obj}.ptr) {\n\t\t${local} = ${value_from_obj(t[1..], obj, param)}\n\t}'
		}
		.dict {
			key, val := map_parts(t)
			items := '${local}_items'
			'${fetch}\n\t${items} := vcraft.dict_items(${obj}, ${vstring_literal(param)}) or { return unsafe { nil } }\n' +
				'\tmut ${local} := ${t}{}\n' +
				'\tfor ${local}_k := 0; ${local}_k < ${items}.len; ${local}_k += 2 {\n' +
				'\t\t${local}[${value_from_obj(key, '${items}[${local}_k]', param)}] = ' +
				'${value_from_obj(val, '${items}[${local}_k + 1]', param)}\n\t}'
		}
		// Read as the slice of the same element, then held to exactly N items.
		.fixed {
			n, element := fixed_parts(t)
			seq := '${local}_seq'
			'${reader_expr(.seq, seq, index, func, param, '[]' + element)}\n' +
				'\tif ${seq}.len != ${n} {\n' +
				"\t\tvcraft.raise_value_error('${func}() argument ${param}: expected ${n} items, got \${${seq}.len}')\n" +
				'\t\treturn unsafe { nil }\n\t}\n' +
				'\tmut ${local} := ${t}{}\n' +
				'\tfor ${local}_k in 0 .. ${n} {\n\t\t${local}[${local}_k] = ${seq}[${local}_k]\n\t}'
		}
		else { "vcraft.raise_type_error('${func}() argument ${param}: a multi-value type cannot be passed in')\n\treturn unsafe { nil }" }
	}
}
